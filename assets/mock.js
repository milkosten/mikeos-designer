// A tiny SVG thumbnail rendered as a data: URI (no external assets).
function thumbFor(title, style) {
  const brand = STYLE_BRAND[style] || "#6d8bff";
  const t = String(title || "Untitled").slice(0, 18);
  const svg = `<svg xmlns='http://www.w3.org/2000/svg' width='320' height='200'>
    <rect width='320' height='200' fill='#f7f8fb'/>
    <rect width='320' height='54' fill='${brand}'/>
    <text x='16' y='34' font-family='system-ui,sans-serif' font-size='18' fill='#fff'>${t}</text>
    <rect x='16' y='74' width='180' height='14' rx='4' fill='#d7dbe6'/>
    <rect x='16' y='98' width='240' height='10' rx='4' fill='#e3e6ef'/>
    <rect x='16' y='118' width='210' height='10' rx='4' fill='#e3e6ef'/>
    <rect x='16' y='150' width='90' height='30' rx='6' fill='${brand}'/>
  </svg>`;
  return "data:image/svg+xml;utf8," + encodeURIComponent(svg);
}

function defaultBrief(title, style) {
  return {
    brand: title,
    tagline: "Describe it, ship it. No code.",
    tone: style === "corporate" ? "professional, trustworthy" : "warm, confident",
    sections: ["Hero", "Features", "Call to action", "Footer"],
  };
}

const store = new Map();
let seq = 0;
const rid = () => (Math.random().toString(36) + "000000").slice(2, 8);

function seed() {
  const id = "demo01";
  store.set(id, {
    id, title: "Acme Studio", page_type: "landing", style: "modern", interactive: false,
    brief: defaultBrief("Acme Studio", "modern"),
    pages: [
      { file: "index.html", html: demoLanding("Acme Studio", "modern", false) },
      { file: "about.html", html: demoAbout("Acme Studio") },
    ],
    url: `https://designer.osmike.com/${id}/`,
    thumbnail: thumbFor("Acme Studio", "modern"),
    visibility: "private",
    versions: [
      { version_id: "v1", note: "Initial generation", created_at: new Date(Date.now() - 864e5).toISOString() },
    ],
    created_at: new Date(Date.now() - 864e5).toISOString(),
    updated_at: new Date(Date.now() - 3600e3).toISOString(),
  });
}
seed();

function shape(p) {
  return { id: p.id, title: p.title, page_type: p.page_type, style: p.style,
           interactive: p.interactive, brief: p.brief, pages: p.pages, url: p.url,
           thumbnail: p.thumbnail, visibility: p.visibility,
           created_at: p.created_at, updated_at: p.updated_at };
}

function pushVersion(p, note) {
  p.versions = p.versions || [];
  p.versions.unshift({ version_id: "v" + (p.versions.length + 1), note, created_at: new Date().toISOString() });
  // keep a snapshot of pages for revert
  p.versions[0]._pages = JSON.parse(JSON.stringify(p.pages));
  p.versions[0]._style = p.style;
}

// Stream a project's pages to onEvent as chunked `token` frames, framed by
// progress/brief/page_start/page_done/done — the shared shape for create/edit/brief/restyle.
async function streamProject(p, onEvent, { withBrief = false, note = "Edited", progressLabels } = {}) {
  const emit = (e) => { if (onEvent) onEvent(e); };
  const labels = progressLabels || ["Understanding your request", "Planning the layout"];
  for (const stage of labels) { emit({ type: "progress", stage, detail: "" }); await wait(400); }
  if (withBrief) { emit({ type: "brief", brief: p.brief }); await wait(350); }
  emit({ type: "progress", stage: "Designing the page", detail: p.pages[0].file }); await wait(250);
  for (const pg of p.pages) {
    emit({ type: "page_start", file: pg.file });
    const html = pg.html;
    // chunk the html into ~24 pieces so the live preview visibly builds up
    const parts = Math.min(24, Math.max(6, Math.floor(html.length / 90)));
    const size = Math.ceil(html.length / parts);
    for (let o = 0; o < html.length; o += size) {
      emit({ type: "token", file: pg.file, delta: html.slice(o, o + size) });
      await wait(70);
    }
    emit({ type: "page_done", file: pg.file });
    await wait(120);
  }
  emit({ type: "progress", stage: "Publishing", detail: "" }); await wait(300);
  pushVersion(p, note);
  p.updated_at = new Date().toISOString();
  const proj = shape(p);
  emit({ type: "done", project: proj });
  return proj;
}

export const mockApi = {
  async health() { return { status: "ok" }; },
  async meta() {
    await wait(120);
    return {
      styles: [
        { id: "modern",  name: "Modern",  description: "Clean, spacious, gradients" },
        { id: "minimal", name: "Minimal", description: "Black & white, typographic" },
        { id: "playful", name: "Playful", description: "Rounded, colorful, friendly" },
        { id: "corporate", name: "Corporate", description: "Trustworthy and structured" },
        { id: "brutalist", name: "Brutalist", description: "Bold borders, raw type" },
      ],
    };
  },
  async listProjects() {
    await wait(120);
    return [...store.values()]
      .sort((a, b) => (b.updated_at > a.updated_at ? 1 : -1))
      .map((p) => ({ id: p.id, title: p.title, page_type: p.page_type, style: p.style,
        updated_at: p.updated_at, url: p.url, thumbnail: p.thumbnail }));
  },
  async getProject(id) { await wait(100); const p = store.get(id); if (!p) throw new Error("not found"); return shape(p); },
  async getFiles(id)   { await wait(80);  const p = store.get(id); if (!p) throw new Error("not found"); return { pages: p.pages }; },

  async createProject({ prompt, page_type, style, title, interactive }) {
    await wait(900);
    const id = rid();
    const t = title || (prompt ? prompt.slice(0, 32) : "Untitled") + (++seq ? "" : "");
    const p = {
      id, title: t, page_type: page_type === "auto" ? "landing" : (page_type || "landing"),
      style: style || "modern", interactive: !!interactive,
      brief: defaultBrief(t, style || "modern"),
      pages: [
        { file: "index.html", html: demoLanding(t, style || "modern", !!interactive) },
        { file: "about.html", html: demoAbout(t) },
      ],
      url: `https://designer.osmike.com/${id}/`, thumbnail: thumbFor(t, style || "modern"),
      visibility: "private", versions: [],
      created_at: new Date().toISOString(), updated_at: new Date().toISOString(),
    };
    pushVersion(p, "Initial generation");
    store.set(id, p);
    return shape(p);
  },

  async createProjectStream(payload, onEvent) {
    const proj = await this.createProject(payload);
    const p = store.get(proj.id);
    // reset versions so the streamed "done" produces the initial one only
    p.versions = [];
    return streamProject(p, onEvent, {
      withBrief: true, note: "Initial generation",
      progressLabels: ["Understanding your request", "Detecting page type", "Planning the layout"],
    });
  },

  async editStream(id, { instruction, selector, outer_html }, onEvent) {
    const p = store.get(id); if (!p) throw new Error("not found");
    const idx = p.pages.findIndex((x) => x.file === "index.html") || 0;
    const note = selector ? `Edited <${(outer_html || "").replace(/^\s*<\s*([a-z0-9]+).*/is, "$1") || "element"}>: ${instruction}`
                          : `Refine: ${instruction}`;
    // Simulate a targeted change: inject a banner into index.html.
    p.pages[idx].html = p.pages[idx].html.replace("</body>",
      `  <div style="position:fixed;bottom:0;left:0;right:0;background:#111;color:#fff;padding:10px;text-align:center;font-family:system-ui">✎ ${String(instruction).replace(/</g, "").slice(0, 80)}</div>\n</body>`);
    return streamProject(p, onEvent, { note, progressLabels: ["Applying your change"] });
  },

  async getBrief(id) { await wait(80); const p = store.get(id); if (!p) throw new Error("not found"); return { brief: p.brief }; },

  async putBriefStream(id, brief, onEvent) {
    const p = store.get(id); if (!p) throw new Error("not found");
    p.brief = brief;
    // rebuild the hero title/tagline from the brief
    const t = brief.brand || p.title;
    p.title = t; p.thumbnail = thumbFor(t, p.style);
    p.pages[0].html = demoLanding(t, p.style, p.interactive)
      .replace("Describe it, ship it. No code.", (brief.tagline || "").replace(/</g, "") || "Describe it, ship it. No code.");
    return streamProject(p, onEvent, { withBrief: true, note: "Rebuilt from brief",
      progressLabels: ["Re-reading the brief", "Rebuilding the page"] });
  },

  async restyleStream(id, style, onEvent) {
    const p = store.get(id); if (!p) throw new Error("not found");
    p.style = style;
    p.thumbnail = thumbFor(p.title, style);
    p.pages = [
      { file: "index.html", html: demoLanding(p.title, style, p.interactive) },
      { file: "about.html", html: demoAbout(p.title) },
    ];
    return streamProject(p, onEvent, { note: `Restyled to ${style}`,
      progressLabels: ["Re-rendering in the new style"] });
  },

  async versions(id) {
    await wait(80); const p = store.get(id); if (!p) throw new Error("not found");
    return (p.versions || []).map((v) => ({ version_id: v.version_id, note: v.note, created_at: v.created_at }));
  },
  async revert(id, versionId) {
    await wait(300); const p = store.get(id); if (!p) throw new Error("not found");
    const v = (p.versions || []).find((x) => x.version_id === versionId);
    if (v && v._pages) { p.pages = JSON.parse(JSON.stringify(v._pages)); if (v._style) p.style = v._style; }
    p.thumbnail = thumbFor(p.title, p.style);
    pushVersion(p, `Reverted to ${versionId}`);
    p.updated_at = new Date().toISOString();
    return shape(p);
  },

  async publish(id) {
    await wait(400);
    const p = store.get(id); if (!p) throw new Error("not found");
    p.visibility = "public"; p.updated_at = new Date().toISOString();
    return { url: p.url, visibility: "public" };
  },
  async deleteProject(id) { await wait(200); store.delete(id); return { deleted: true }; },

  // mock-only helper the app uses to render previews without a live host
  _htmlFor(id, file) {
    const p = store.get(id); if (!p) return "<h1>not found</h1>";
    const pg = p.pages.find((x) => x.file === file) || p.pages[0];
    return pg.html;
  },
};
